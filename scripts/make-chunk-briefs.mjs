// 입력: legacy/analysis/_plan.json (plan-analysis.mjs 결과), legacy/docs/queries/*.m.txt (파워쿼리 M 코드)
// 출력: legacy/analysis/chunks/<ID>.md  (담당 범위 + 공통 지시), legacy/analysis/out/ (결과가 저장될 폴더)
// 모든 결과는 git에 올라가지 않는 legacy/ 아래에만 저장합니다.

import fs from "node:fs";
import path from "node:path";

const root = path.resolve("legacy", "analysis");
const plan = JSON.parse(fs.readFileSync(path.join(root, "_plan.json"), "utf8"));
const queriesDir = path.resolve("legacy", "docs", "queries");

// 파워쿼리 M 코드 덩어리 추가
const mFiles = fs.readdirSync(queriesDir).filter((f) => f.endsWith(".m.txt"));
for (const f of mFiles) {
  const full = path.join("legacy", "docs", "queries", f);
  const text = fs.readFileSync(path.resolve(full), "utf8");
  const n = text.split("\n").length;
  const book = f.replace(/-\d+\.m\.txt$/, "");
  const tag = book.includes("서무") ? "B" : book.includes("배치표") ? "C" : "A";
  const split = tag === "A" ? 2 : 1;
  for (let k = 0; k < split; k++) {
    const startLine = Math.floor((n * k) / split) + 1;
    const endLine = Math.floor((n * (k + 1)) / split);
    plan.push({
      id: `${tag}M${split > 1 ? k + 1 : ""}`,
      workbook: book,
      kind: "powerquery",
      chars: text.length / split,
      lines: endLine - startLine + 1,
      parts: [{ file: full, module: "파워쿼리 M 코드", startLine, endLine, chars: Math.round(text.length / split) }],
      note: tag === "B" ? "이 M 코드는 경력대장(간호직) 파일의 M 코드와 대부분 같을 수 있습니다. Bash로 두 파일을 비교(diff)해서 다른 부분 위주로 읽되, 다른 부분의 앞뒤 맥락은 충분히 읽으세요. 같은 부분은 '간호직과 동일(줄 범위)'로 적고, 쿼리 이름과 하는 일은 빠짐없이 적으세요." : "",
    });
  }
}
fs.writeFileSync(path.join(root, "_plan.json"), JSON.stringify(plan, null, 2), "utf8");

